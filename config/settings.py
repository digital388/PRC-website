# Database
# https://docs.djangoproject.com/en/6.1/ref/settings/#databases
#
# Values come from the DATABASE SETUP block near the top of this file.
# Set the matching cPanel environment variables to override that block
# (environment variables win when they are present).
_db_name = _env("DJANGO_DB_NAME", DB_NAME).strip()
_db_user = _env("DJANGO_DB_USER", DB_USER).strip()
_db_password = _env("DJANGO_DB_PASSWORD", DB_PASSWORD)
_db_host = _env("DJANGO_DB_HOST", DB_HOST).strip()
_db_port = _env("DJANGO_DB_PORT", DB_PORT).strip()

# MySQL is used as soon as a database name is given -- either in the block at
# the top of this file or through DJANGO_DB_NAME. DJANGO_DB=mysql forces it.
_use_mysql = bool(_db_name) or _env("DJANGO_DB", "").strip().lower() == "mysql"

if _use_mysql:
    if not _db_name or not _db_user:
        raise ImproperlyConfigured(
            "MySQL is switched on, but the database name or user is empty. "
            "Fill in DB_NAME and DB_USER in the DATABASE SETUP block at the "
            "top of config/settings.py, or set DJANGO_DB_NAME / "
            "DJANGO_DB_USER in the cPanel app's environment variables."
        )
    DATABASES = {
        "default": {
            "ENGINE": "django.db.backends.mysql",
            "NAME": _db_name,
            "USER": _db_user,
            "PASSWORD": _db_password,
            "HOST": _db_host or "localhost",
            "PORT": _db_port or "3306",
            "CONN_MAX_AGE": 60,
            "OPTIONS": {
                "charset": "utf8mb4",
                "init_command": "SET sql_mode='STRICT_TRANS_TABLES'",
            },
        }
    }
else:
    # Fail loudly instead of silently serving an empty local SQLite database
    # on the live server. (Set DJANGO_DB=sqlite to use SQLite in production
    # on purpose.)
    if not DEBUG and _env("DJANGO_DB", "").strip().lower() != "sqlite":
        raise ImproperlyConfigured(
            "The site is running with DEBUG=False but no MySQL database is "
            "configured, so it would serve an empty SQLite database. Fill in "
            "DB_NAME and DB_USER in the DATABASE SETUP block at the top of "
            "config/settings.py, or set DJANGO_DB_NAME / DJANGO_DB_USER in "
            "the cPanel app's environment variables."
        )
    DATABASES = {
        "default": {
            "ENGINE": "django.db.backends.sqlite3",
            "NAME": BASE_DIR / "db.sqlite3",
        }
    }


